const {workbenchAccess}=require('../../workbench/test_api.cjs');
const {createRequire}=require('module');
const {chromium}=require('../../workbench/test_api.cjs');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.PAPER_TEST_CHROME||undefined});
 const page=await browser.newPage({viewport:{width:1400,height:1000}});const errors=[];page.on('pageerror',e=>errors.push(e.message));const access=await workbenchAccess(page);
 const initial=await (await page.request.get(access.base+'/api/state')).json();
 const fixtures=initial.papers.filter(p=>p.candidate_order!==null&&p.acquisition==='available'&&p.decision==='unreviewed'&&p.assessment&&!p.metadata.out_of_scope).slice(0,4);
 if(!fixtures.length)throw Error('No assessed PDF fixtures');
 let snapshot={...initial,papers:fixtures};let refreshes=0;
 await page.route('**/api/state*',async route=>{refreshes++;await route.fulfill({json:snapshot})});
 await page.goto(access.authenticatedUrl);await page.waitForSelector('article.card');
 const key=fixtures[0].id+':novelty';const details=page.locator('details[data-detail="'+key+'"]');
 await details.locator('summary').click();await page.evaluate(()=>window.keepNode=document.querySelector('article.card'));
 await page.waitForTimeout(11000);
 if(!await details.evaluate(d=>d.open))throw Error('Collapsed during automatic refresh');
 if(!await page.evaluate(()=>window.keepNode===document.querySelector('article.card')))throw Error('Unchanged article was replaced');
 snapshot=JSON.parse(JSON.stringify(snapshot));snapshot.papers[0].assessment.novelty+=' VERIFIED UPDATE';
 await page.locator('#paperSearch').focus();await page.locator('#paperSearch').fill('');
 await page.waitForFunction(()=>document.querySelector('details[data-detail$=":novelty"]').textContent.includes('VERIFIED UPDATE'));
 if(!await details.evaluate(d=>d.open))throw Error('Collapsed when assessment updated');
 await details.locator('summary').click();await page.waitForTimeout(5500);
 if(await details.evaluate(d=>d.open))throw Error('Closed details reopened');
 if(await page.locator('details.tools').isVisible())throw Error('Management controls still visible');
 if(await page.locator('details[data-detail$=":more"]').count())throw Error('Removed source controls still present');
 await page.screenshot({path:'/private/tmp/paper-workbench-clean.png',fullPage:false});
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({automaticRefreshes:refreshes,expandedStatePreserved:true,unchangedNodesPreserved:true,changedDataRefreshed:true,closedStatePreserved:true,JSerrors:errors.length}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
